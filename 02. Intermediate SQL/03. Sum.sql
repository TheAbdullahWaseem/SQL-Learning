--Top 5 Customers by Spending
select customer_id, sum(amount) from payment group by customer_id order by sum(amount) desc limit 5;
--Show customers whose total spending is between 100 and 200.
select customer_id, sum(amount) from payment group by customer_id having sum(amount) between 100 and 200; 
--Calculate total revenue generated by customers where active = 1
select sum(p.amount) from customer c 

--Show cumulative revenue generated by each customer payment.

with customer_revenue as (
	select
		customer_id,
		payment_date,
		amount,
		sum(amount) over (
			partition by customer_id 
			order by payment_date
		) as running_total
	from payment
)
select *
from customer_revenue;



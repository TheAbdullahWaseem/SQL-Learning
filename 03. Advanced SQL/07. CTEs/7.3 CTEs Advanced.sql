51. CTE With Window Functions Inside 

--In real jobs, you will constantly see:

WITH cte_name AS (
    SELECT
        ...,
        ROW_NUMBER() OVER (...),
        SUM(...) OVER (...),
        LAG(...) OVER (...)
    FROM table
)
SELECT *
FROM cte_name;

--This pattern is everywhere.

First Question

--What Does "CTE With Window Functions Inside" Mean?
--Simply:

WITH cte_name AS (
    SELECT
        columns,
        window_function(...)
    FROM table
)
SELECT *
FROM cte_name;

--Window functions are calculated INSIDE the CTE.
--The resulting dataset is then used later.

Mental Model
--Think:

Raw Data
    ↓
Window Function Analysis
    ↓
Store Result in CTE
    ↓
Further Analysis

--Why Do Professionals Use This?
--Because window functions often create:

Ranks
Running Totals
Previous Values
Moving Averages
Percentages

--And those results are often needed later.
--A CTE allows us to save them and continue working.

--Example 1 — Customer Revenue Ranking

--Business Question
--Rank customers by revenue.

--Step 1
--Create revenue dataset.

WITH customer_revenue AS (
    SELECT
        customer_id,
        SUM(amount) AS revenue
    FROM payment
    GROUP BY customer_id
)
SELECT *
FROM customer_revenue;

--Now we want ranking.
--Window Function Inside CTE

WITH customer_rankings AS (
    SELECT
        customer_id,
        SUM(amount) AS revenue,
        DENSE_RANK() OVER (
            ORDER BY SUM(amount) DESC
        ) AS revenue_rank
    FROM payment
    GROUP BY customer_id
)
SELECT *
FROM customer_rankings;



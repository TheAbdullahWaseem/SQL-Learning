Writing Block Summary

Recursive CTE — Concept and Basic Syntax

A Recursive CTE is a Common Table Expression that references itself and 
repeatedly executes until a stopping condition is reached. It is used for 
problems involving unknown numbers of levels, such as organizational hierarchies, 
category trees, folder structures, and sequence generation.

Every Recursive CTE contains two parts:

Anchor Query — produces the initial rows.
Recursive Query — references the CTE itself and generates new rows from previous results.

The two parts are combined using UNION ALL.
Basic structure:

WITH RECURSIVE cte_name AS (

    Anchor Query

    UNION ALL

    Recursive Query

)
SELECT *
FROM cte_name;

Execution begins with the anchor query. The recursive query then repeatedly 
runs using the rows already generated by the CTE. The process continues 
until the stopping condition is no longer satisfied.

A classic example generates numbers 1 through 5:

WITH RECURSIVE numbers AS (
    SELECT 1 AS n

    UNION ALL

    SELECT n + 1
    FROM numbers
    WHERE n < 5
)
SELECT *
FROM numbers;

The anchor query generates 1. The recursive query repeatedly adds 1 to 
the previous value, generating 2, 3, 4, and 5. When n reaches 5, 
the condition n < 5 fails and recursion stops.

The essential components of every recursive CTE are:

Anchor Query
Recursive Query
UNION ALL
Stopping Condition

Without a stopping condition, recursion can continue indefinitely, 
making the stopping condition one of the most important parts of recursive CTE design.


--Generate Dates

with recursive dates as (
	select Date '2026-06-01' as n
	
	union all
	
	select n + 1
	from dates
	where n < date '2026-06-16'
)
select *
from dates;


--What is the difference between the Anchor Member and Recursive Member?
--Strong answer:

--	The Anchor Member provides the starting rows for recursion and executes only once.

--	The Recursive Member references the recursive CTE itself and repeatedly generates

54. Replacing Complex Subqueries With CTEs 

--First Question
--Why do people use subqueries?

--Because sometimes a query needs data that must be calculated first.
--Example:

SELECT *
FROM film
WHERE rental_rate >
(
    SELECT AVG(rental_rate)
    FROM film
);

--The subquery calculates:

--When Do Problems Start?
--When subqueries become deeply nested.

--Example:

SELECT ...
FROM (
    SELECT ...
    FROM (
        SELECT ...
        FROM (
            SELECT ...
        ) x
    ) y
) z;

--This becomes difficult to:

--Read
--Debug
--Maintain
--Explain

The Core Idea

--A CTE lets us pull subquery logic out and give it a name.
--Instead of:

SELECT ...
FROM (
    complicated query
)

--we can write:

WITH meaningful_name AS (
    complicated query
)
SELECT ...
FROM meaningful_name;

--Much cleaner.

--Example 1 — Above Average Rental Rate
--Traditional Subquery

SELECT
    film_id,
    title,
    rental_rate
FROM film
WHERE rental_rate >
(
    SELECT AVG(rental_rate)
    FROM film
);

What Happens?

Subquery:

SELECT AVG(rental_rate)
FROM film;

--returns:
--2.98

--Then SQL executes:
--WHERE rental_rate > 2.98


Same Query Using CTE

WITH avg_rate AS (
    SELECT
        AVG(rental_rate) AS average_rate
    FROM film
)
SELECT
    f.film_id,
    f.title,
    f.rental_rate
FROM film f
CROSS JOIN avg_rate ar
WHERE f.rental_rate > ar.average_rate;

--CROSS JOIN = every row combines with every row
--CROSS JOIN is used here only to “attach a single aggregated value
--to every row so it can be compared.”

--You can avoid CROSS JOIN completely
--This is actually cleaner:

WITH avg_rate AS (
    SELECT AVG(rental_rate) AS average_rate
    FROM film
)
SELECT
    film_id,
    title,
    rental_rate
FROM film
WHERE rental_rate > (SELECT average_rate FROM avg_rate);


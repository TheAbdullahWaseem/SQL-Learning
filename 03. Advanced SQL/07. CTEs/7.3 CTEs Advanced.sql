WITH RECURSIVE category_tree AS (

    SELECT
        category_id,
        category_name,
        parent_category_id,
        1 AS level
    FROM product_categories
    WHERE category_name = 'Electronics'

    UNION ALL

    SELECT
        pc.category_id,
        pc.category_name,
        pc.parent_category_id,
        ct.level + 1
    FROM product_categories pc
    JOIN category_tree ct
        ON pc.parent_category_id = ct.category_id

)

